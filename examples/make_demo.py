"""Generate synthetic raw-data files (AncestryDNA, 23andMe and MyHeritage layouts) for demos and tests.

The genotypes are random with realistic allele frequencies at the panel sites, so the demo report is
illustrative only and corresponds to no real person. mtDNA is written as rCRS plus 3010A so Haplogrep3
calls H1; the sample is female (no Y rows), so the Y caller is skipped.
"""
from __future__ import annotations

import csv
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MARKERS = HERE.parent / "gnomancer" / "data" / "markers.tsv"
RCRS = HERE.parent / "gnomancer" / "data" / "rCRS_NC_012920.1.fasta"

# Build-37 anchor SNPs used by `snps` to detect the assembly.
ANCHORS = [("rs3094315", "1", 752566), ("rs3131972", "1", 752721), ("rs11928389", "3", 50927009),
           ("rs2500347", "1", 144938320), ("rs964481", "1", 142478260)]
CHR_LEN = {str(i): L for i, L in zip(range(1, 23), [249e6, 243e6, 198e6, 191e6, 181e6, 171e6, 159e6, 146e6, 141e6, 135e6, 135e6, 134e6, 115e6, 107e6, 102e6, 90e6, 81e6, 78e6, 59e6, 63e6, 48e6, 51e6])}
CHR_LEN["X"] = 155e6


def main(outdir: str, seed: int = 7, n_filler: int = 20000):
    rng = random.Random(seed)
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    rows = []  # (rsid, chrom, pos, a1, a2)
    with open(MARKERS, newline="") as f:
        lines = [l for l in f if l.strip() and not l.startswith("#")]
    markers = list(csv.DictReader(lines, delimiter="\t"))
    # Positions for panel sites are not needed for interpretation; use deterministic fake positions on the stated chromosome.
    fake_chr = {}
    for m in markers:
        ch = rng.choice(list(CHR_LEN)) if m["rsid"] not in fake_chr else fake_chr[m["rsid"]]
        if m["gene"].startswith("G6PD"):
            ch = "X"
        pos = rng.randint(1_000_000, int(CHR_LEN[ch]) - 1_000_000)
        p_eff = 0.08 if m["category"] in ("carrier",) else 0.35
        a = [m["effect"] if rng.random() < p_eff else m["ref"] for _ in range(2)]
        rows.append((m["rsid"], ch, pos, a[0], a[1]))
    for rsid, ch, pos in ANCHORS:
        rows.append((rsid, ch, pos, "A", "A"))
    for i in range(n_filler):
        ch = rng.choice(list(CHR_LEN))
        pos = rng.randint(100_000, int(CHR_LEN[ch]) - 100_000)
        ref, alt = rng.sample("ACGT", 2)
        p = rng.random()
        g = [alt if rng.random() < p else ref for _ in range(2)]
        if ch == "X":
            g = [g[0], g[0]]  # keep a little X heterozygosity by leaving some hets below
            if rng.random() < 0.25:
                g = [ref, alt]
        rows.append((f"rs{90000000 + i}", ch, pos, g[0], g[1]))
    ref_mt = "".join(l.strip() for l in open(RCRS) if not l.startswith(">"))
    for k, pos in enumerate(sorted(set(range(100, 16500, 73)) | {3010})):
        a = "A" if pos == 3010 else ref_mt[pos - 1]
        rows.append((f"rs{80000000 + k}", "MT", pos, a, a))
    order = {**{str(i): i for i in range(1, 23)}, "X": 23, "MT": 26}
    rows.sort(key=lambda r: (order[r[1]], r[2]))

    anc = out / "demo_AncestryDNA.txt"
    with open(anc, "w", newline="") as f:
        f.write("#AncestryDNA raw data download\r\n#This file was generated by AncestryDNA (synthetic demo)\r\n#Data was collected using AncestryDNA array version: V2.0\r\n")
        f.write("rsid\tchromosome\tposition\tallele1\tallele2\r\n")
        for rsid, ch, pos, a1, a2 in rows:
            c = {"X": "23", "MT": "26"}.get(ch, ch)
            f.write(f"{rsid}\t{c}\t{pos}\t{a1}\t{a2}\r\n")
    ttam = out / "demo_23andMe.txt"
    with open(ttam, "w") as f:
        f.write("# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2024 (synthetic demo)\n# rsid\tchromosome\tposition\tgenotype\n")
        for rsid, ch, pos, a1, a2 in rows:
            g = a1 if ch == "MT" else a1 + a2
            f.write(f"{rsid}\t{ch}\t{pos}\t{g}\n")
    mh = out / "demo_MyHeritage.csv"
    with open(mh, "w") as f:
        f.write("##fileformat=MyHeritage\n#MyHeritage DNA raw data (synthetic demo)\nRSID,CHROMOSOME,POSITION,RESULT\n")
        for rsid, ch, pos, a1, a2 in rows:
            f.write(f'"{rsid}","{ch}","{pos}","{a1}{a2}"\n')
    print(anc, ttam, mh, sep="\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "demo")
