"""Rebuild gnomancer/data/dosage_genes.tsv from ClinGen's dosage-sensitivity curation (CC0).

ClinGen scores each curated gene for haploinsufficiency (does losing one copy cause disease?) and
triplosensitivity (does an extra copy?). Score 3 = sufficient evidence; 30 = the gene is associated with an
autosomal recessive condition, so losing one copy is a carrier state; 40 = dosage sensitivity unlikely.
This is the lens for reading copy-number and structural variants: a deletion matters when it removes a gene
that cannot do without both copies.

Usage: python examples/build_dosage.py   (needs network)
"""
from __future__ import annotations

import csv
import io
import subprocess
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "gnomancer" / "data" / "dosage_genes.tsv"
URL = "https://ftp.clinicalgenome.org/ClinGen_gene_curation_list_GRCh{}.tsv"
REGION_URL = "https://ftp.clinicalgenome.org/ClinGen_region_curation_list_GRCh{}.tsv"


def fetch(build: int) -> dict:
    text = subprocess.run(["curl", "-fsSL", URL.format(build)], capture_output=True, text=True, check=True).stdout
    date = text.split("\n")[1].lstrip("#").strip()
    lines = [l for l in text.split("\n") if l and (not l.startswith("#") or l.startswith("#Gene Symbol"))]
    lines[0] = lines[0].lstrip("#")
    out = {}
    for r in csv.DictReader(io.StringIO("\n".join(lines)), delimiter="\t"):
        loc = r["Genomic Location"]
        if ":" not in loc or "-" not in loc:
            continue
        chrom, span = loc.replace("chr", "").split(":")
        start, end = span.split("-")
        out[r["Gene Symbol"]] = dict(chrom=chrom, start=int(start), end=int(end), hi=r["Haploinsufficiency Score"], ts=r["Triplosensitivity Score"],
                                     hi_text=r["Haploinsufficiency Description"])
    return out, date


def fetch_regions(build: int) -> dict:
    """Recurrent regions (22q11.2, 17p12 and the like) with sufficient evidence in either direction."""
    text = subprocess.run(["curl", "-fsSL", REGION_URL.format(build)], capture_output=True, text=True, check=True).stdout
    lines = [l for l in text.split("\n") if l and (not l.startswith("#") or l.startswith("#ISCA ID"))]
    lines[0] = lines[0].lstrip("#")
    out = {}
    for r in csv.DictReader(io.StringIO("\n".join(lines)), delimiter="\t"):
        loc = r["Genomic Location"]
        if ":" not in loc or "-" not in loc or "3" not in (r["Haploinsufficiency Score"], r["Triplosensitivity Score"]):
            continue
        chrom, span = loc.replace("chr", "").split(":")
        start, end = span.split("-")
        out[r["ISCA Region Name"].strip()] = dict(chrom=chrom, start=int(start), end=int(end), hi=r["Haploinsufficiency Score"], ts=r["Triplosensitivity Score"])
    return out


def main() -> None:
    b37, _ = fetch(37)
    b38, date = fetch(38)
    r37, r38 = fetch_regions(37), fetch_regions(38)
    num = lambda v: v if v.lstrip("-").isdigit() else ""  # noqa: E731
    with open(OUT, "w") as f:
        f.write(f"# ClinGen dosage sensitivity curation, {date} (CC0). Generated by examples/build_dosage.py; do not edit by hand.\n"
                "# hi/ts: 3 sufficient evidence, 2 emerging, 1 little, 0 none, 30 autosomal recessive gene, 40 dosage sensitivity unlikely.\n"
                "# kind: gene, or region for a recurrent copy-number region (listed only when either score is 3).\n"
                "gene\tkind\tchrom\tstart37\tend37\tstart38\tend38\thi\tts\n")
        n = 0
        for kind, x37, x38 in (("gene", b37, b38), ("region", r37, r38)):
            for g in sorted(set(x37) | set(x38)):
                a, b = x37.get(g), x38.get(g)
                ref = b or a
                f.write("\t".join(map(str, [g, kind, ref["chrom"], a["start"] if a else "", a["end"] if a else "", b["start"] if b else "", b["end"] if b else "",
                                            num(ref["hi"]), num(ref["ts"])])) + "\n")
                n += 1
    print(f"{n} rows written to {OUT}")


if __name__ == "__main__":
    main()
