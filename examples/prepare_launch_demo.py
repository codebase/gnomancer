"""Package only the generated synthetic sample and report for the public walkthrough.

Usage: python examples/prepare_launch_demo.py REPORT_DIR SYNTHETIC_INPUT_DIR
Run examples/make_demo.py and the lightweight CLI command first.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main(report_dir: Path, input_dir: Path) -> None:
    from gnomancer.mcp_server import lookup

    sample = input_dir / "demo_AncestryDNA.txt"
    raw = sample.read_text()
    # Refuse to package an ordinary vendor export accidentally passed to this helper.
    if "#This file was generated by AncestryDNA (synthetic demo)" not in raw:
        raise ValueError("input must come from examples/make_demo.py")
    dest = ROOT / "site" / "demo"
    dest.mkdir(parents=True, exist_ok=True)
    banner = (
        '<aside style="padding:14px 20px;background:#efe9fd;color:#3d177c;'
        'font:600 14px/1.5 system-ui;border-bottom:1px solid #d5c6ef">'
        'SYNTHETIC DEMO — No real person. Artificial genotypes and positions. '
        'Haplogroups, ClinVar and PharmCAT were skipped. '
        '<a href="./" style="color:inherit">Back to the walkthrough</a></aside>'
    )
    report = (report_dir / "REPORT.html").read_text()
    report = report.replace("<head>", '<head><meta name="robots" content="noindex">', 1)
    report = report.replace("<body>", "<body>" + banner, 1)
    report = report.replace(
        '<a class="btn" href="pgx-card.pdf">Pharmacist card</a>',
        '<a class="btn" href="./">Synthetic demo</a>',
    )
    report = re.sub(r'<p class="caption"><a class="btn" href="pgx-card.pdf">.*?</p>', "", report)
    report = report.replace(
        "To share with a clinician, print this page or hand over the pharmacist card (pgx-card.pdf).",
        "This synthetic report is for demonstration only and must not be used for clinical decisions.",
    )
    (dest / "report.html").write_text(report)
    (dest / "report.md").write_text(
        "> SYNTHETIC DEMO — No real person. Artificial genotypes and positions. "
        "Haplogroups, ClinVar and PharmCAT were skipped. Not clinical data.\n\n"
        + (report_dir / "REPORT.md").read_text()
    )
    (dest / "synthetic-sample.txt").write_text(raw)
    result = lookup("rs762551", str(report_dir.resolve()))
    assert result["genotype"] == "CA" and result["interpretation"] == "intermediate"
    (dest / "lookup.json").write_text(json.dumps(result, indent=2) + "\n")
    manifest = {
        "synthetic": True,
        "generator": "examples/make_demo.py",
        "seed": 7,
        "sample_sha256": hashlib.sha256(raw.encode()).hexdigest(),
        "site_count": 20342,
        "skipped": ["Y haplogroup", "mtDNA haplogroup", "ClinVar", "PharmCAT"],
        "command": "gnomancer demo_AncestryDNA.txt --out demo_report --no-y --no-mt --no-clinvar --no-pharmcat",
        "lookup": result,
        "model_conversation": "None; the walkthrough shows an illustrative question and actual tool output.",
    }
    (dest / "provenance.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Packaged synthetic demo in {dest}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
